def na_tabela(produto) -> bool:
    """O produto está na tabela comercial vigente."""
    return _normalizar(getattr(produto, "sku_key", None)) in _CHAVES


def so_da_tabela(produtos):
    """Os produtos que estão na tabela, na ordem em que vieram."""
    return [p for p in produtos if na_tabela(p)]
